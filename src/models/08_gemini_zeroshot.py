#!/usr/bin/env python
"""
08_gemini_zeroshot.py — cross-vendor zero-shot check with Google gemini-2.5-flash.

Runs the SAME clinician-informed, prevalence-free system prompt and the SAME
3-class structured-output tool used for the Claude models, zero-shot over the
serialized patient narratives, across seeds 0-2 at temperature 1.0.

Inputs  (generated by earlier pipeline steps):
    data/narratives.json      # {"narratives":[...], "labels_bin":[...], "SYSTEM_V2_no_prevalence": "..."}
                              # (produced by src/03_fewshot_llm.py --dump-stage, or build from serialize.py)
Output:
    results/gemini_zeroshot_metrics.json
    results/gemini_zeroshot_percase.csv

Auth: set GEMINI_API_KEY in the environment. The free tier has a *daily* request
cap; a full 3-seed run is ~423 calls. If you hit HTTP 429 RESOURCE_EXHAUSTED,
wait for the Pacific-midnight reset or use a paid-tier key.
"""
import os, json, csv
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT  = os.path.join(ROOT, "results"); os.makedirs(OUT, exist_ok=True)
STAGE = os.path.join(ROOT, "data", "narratives.json")

stage = json.load(open(STAGE))
narr  = stage["narratives"]
ybin  = np.asarray(stage["labels_bin"])
V2    = stage["SYSTEM_V2_no_prevalence"]      # prevalence-free clinician-informed system prompt

GEMINI_MODEL = os.environ.get("GEMINI_MODEL", "gemini-2.5-flash")
KEY = os.environ["GEMINI_API_KEY"]            # never hardcode; set in your shell

import urllib.request, urllib.error, time

tool = {"function_declarations": [{
    "name": "classify_patient",
    "description": "Record the 10-year bipolar prognosis prediction.",
    "parameters": {"type": "object", "properties": {
        "brief_reasoning": {"type": "string"},
        "p_none": {"type": "number"}, "p_subthreshold": {"type": "number"}, "p_full": {"type": "number"},
        "predicted_class": {"type": "string", "enum": ["None", "Subthreshold", "Full"]}},
        "required": ["p_none", "p_subthreshold", "p_full", "predicted_class"]}}]}


def classify_t(narrative, seed, temp=1.0, sysprompt=V2, retries=4, model=GEMINI_MODEL):
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={KEY}"
    body = {
        "systemInstruction": {"parts": [{"text": sysprompt}]},
        "contents": [{"role": "user", "parts": [{"text": narrative}]}],
        "tools": [tool],
        "toolConfig": {"functionCallingConfig": {"mode": "ANY", "allowedFunctionNames": ["classify_patient"]}},
        "generationConfig": {"temperature": temp, "maxOutputTokens": 1200, "thinkingConfig": {"thinkingBudget": 0}, "seed": seed}}
    for a in range(retries):
        try:
            req = urllib.request.Request(url, data=json.dumps(body).encode(), headers={"Content-Type": "application/json"})
            with urllib.request.urlopen(req, timeout=60) as r:
                resp = json.load(r)
            c = resp["candidates"][0]
            if c.get("finishReason") == "MALFORMED_FUNCTION_CALL":
                if a < retries - 1:
                    time.sleep(1)
                    continue
                return {"__error__": "MALFORMED"}
            for pt in c.get("content", {}).get("parts", []):
                if "functionCall" in pt:
                    return pt["functionCall"]["args"]
            if a < retries - 1:
                time.sleep(1)
                continue
            return {"__error__": "no_call"}
        except urllib.error.HTTPError as e:
            if e.code in (429, 500, 503) and a < retries - 1:
                time.sleep(2 ** a)
                continue
            return {"__error__": f"HTTP {e.code}"}
        except Exception as e:
            if a < retries - 1:
                time.sleep(2 ** a)
                continue
            return {"__error__": f"{type(e).__name__}"}


t0 = time.time()
gemini_seeds = {}
for seed in [0, 1, 2]:
    pf = np.full(141, np.nan)
    nerr = 0
    for i in range(141):
        o = classify_t(narr[i], seed=seed, temp=1.0)
        if "__error__" not in o:
            pf[i] = o.get("p_full", np.nan)
        else:
            nerr += 1
    gemini_seeds[seed] = pf
    print(f"seed {seed}: NaNs={int(np.isnan(pf).sum())} errs={nerr} range=[{np.nanmin(pf):.2f},{np.nanmax(pf):.2f}] ({time.time()-t0:.0f}s)")
print("all 3 seeds done")

y = np.array(ybin)
seed_auc = {s: roc_auc_score(y, gemini_seeds[s]) for s in [0, 1, 2]}
print("per-seed AUROC:", {s: round(v, 4) for s, v in seed_auc.items()})
aucs = np.array(list(seed_auc.values()))
print(f"mean AUROC={aucs.mean():.4f}  SD={aucs.std(ddof=1):.4f}")

p_avg = np.nanmean(np.vstack([gemini_seeds[s] for s in [0, 1, 2]]), axis=0)
auc_avg = roc_auc_score(y, p_avg)
fpr, tpr, thr = roc_curve(y, p_avg)
j = np.argmax(tpr - fpr)
t = thr[j]
pred = (p_avg >= t).astype(int)
tp = int(((pred == 1) & (y == 1)).sum())
fn = int(((pred == 0) & (y == 1)).sum())
tn = int(((pred == 0) & (y == 0)).sum())
fp = int(((pred == 1) & (y == 0)).sum())


def ece_score(yt, p, bins=10):
    edges = np.linspace(0, 1, bins + 1)
    e = 0.0
    n = len(yt)
    for i in range(bins):
        mask = ((p > edges[i]) & (p <= edges[i + 1])) if i > 0 else ((p >= edges[i]) & (p <= edges[i + 1]))
        if mask.sum() == 0:
            continue
        e += (mask.sum() / n) * abs(yt[mask].mean() - p[mask].mean())
    return float(e)


rng = np.random.default_rng(42)
idx = np.arange(141)
bs = []
for _ in range(2000):
    b = rng.choice(idx, 141, replace=True)
    if len(np.unique(y[b])) < 2:
        continue
    bs.append(roc_auc_score(y[b], p_avg[b]))
ci = (np.percentile(bs, 2.5), np.percentile(bs, 97.5))
print(f"\nseed-averaged: AUROC={auc_avg:.3f} [{ci[0]:.3f},{ci[1]:.3f}]")
print(f"Youden thr={t:.3f}  Sens={tp/(tp+fn):.3f}  Spec={tn/(tn+fp):.3f}")
print(f"Brier={brier_score_loss(y,p_avg):.3f}  ECE={ece_score(y,p_avg):.3f}")
print(f"\nvs Sonnet 0.728, Haiku 0.737, best ML 0.674, TabFM 0.690")

gemini_metrics = {
    "model": "gemini-2.5-flash", "approach": "zero-shot, clinician-informed prompt (V2, no base rate)",
    "temperature": 1.0, "seeds": [0, 1, 2], "n": 141, "n_pos": 27,
    "per_seed_auroc": {str(s): round(seed_auc[s], 4) for s in [0, 1, 2]},
    "auroc_mean": round(float(aucs.mean()), 4), "auroc_sd": round(float(aucs.std(ddof=1)), 4),
    "auroc_seedavg": round(float(auc_avg), 4), "auroc_95ci": [round(ci[0], 3), round(ci[1], 3)],
    "youden_threshold": round(float(t), 3), "sensitivity": round(tp / (tp + fn), 3), "specificity": round(tn / (tn + fp), 3),
    "brier": round(float(brier_score_loss(y, p_avg)), 3), "ece": round(ece_score(y, p_avg), 3)}
json.dump(gemini_metrics, open(os.path.join(OUT,"gemini_zeroshot_metrics.json"), "w"), indent=2)
print(json.dumps(gemini_metrics, indent=2))